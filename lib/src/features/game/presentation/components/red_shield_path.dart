  static Path _build(List<double> p, Offset center, double scale) {
    Offset at(int i) =>
        Offset(center.dx + (p[i] - width / 2) * scale, center.dy + (p[i + 1] - height / 2) * scale);
    final start = at(0);
    final path = Path()..moveTo(start.dx, start.dy);
    for (var i = 2; i + 5 < p.length; i += 6) {
      final a = at(i), b = at(i + 2), c = at(i + 4);
      path.cubicTo(a.dx, a.dy, b.dx, b.dy, c.dx, c.dy);
    }
    return path..close();
  }

